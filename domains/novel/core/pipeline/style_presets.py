# 下拉首项：不指定（保留空，使用模型默认文风）
UNSPECIFIED = "（不指定 / 默认）"
CUSTOM = "自定义…"


def preset_keys() -> list[str]:
    """下拉项顺序：不指定 → 各作者预设 → 自定义。"""
    return [UNSPECIFIED] + list(STYLE_PRESETS.keys()) + [CUSTOM]


def resolve_style(combo_text: str, custom_text: str = "") -> str:
    """根据下拉选择与自定义文本，解析出最终注入的文风指令。"""
    if combo_text == UNSPECIFIED:
        return ""
    if combo_text == CUSTOM:
        return custom_text.strip()
    return STYLE_PRESETS.get(combo_text, custom_text.strip())
